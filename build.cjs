const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const modules = [];
const ids = new Map();
function bundle(file) {
  file = path.resolve(file);
  if (!file.endsWith('.js')) file += '.js';
  if (ids.has(file)) return ids.get(file);
  const id = modules.length;
  ids.set(file, id);
  modules.push('');
  const source = fs
    .readFileSync(file, 'utf8')
    .replace(
      /require\(['"](\.[^'"]*)['"]\)/g,
      (_, relative) => `__load(${bundle(path.resolve(path.dirname(file), relative))})`,
    );
  modules[id] = `function(module,exports,__load,require){\n${source}\n}`;
  return id;
}
const entry = bundle(path.join(root, 'src/plugin.js'));
fs.writeFileSync(
  path.join(root, 'main.js'),
  `// Generated by build.cjs. Edit src/ instead.\n'use strict';\nconst __modules=[${modules.join(',\n')}];\nconst __cache={};\nfunction __load(id){if(__cache[id])return __cache[id].exports;const module={exports:{}};__cache[id]=module;__modules[id](module,module.exports,__load,require);return module.exports;}\nmodule.exports=__load(${entry});\n`,
);
console.log(`Built main.js (${modules.length} modules)`);
